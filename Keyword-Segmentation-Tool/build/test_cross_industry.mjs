const api = new Function('document', 'XLSX', 'FileReader', 'window', 'setTimeout', 'clearTimeout', code)(doc, XLSX, function () {}, {}, setTimeout, clearTimeout);

function testIndustry(name, keywords) {
  api.state.dataRows = keywords.map(k => [k]);
  api.state.keywordCol = 0;
  api.runClassification();
  const results = api.state.results;
  const dist = {};
  results.forEach(r => dist[r.cat] = (dist[r.cat] || 0) + 1);
  const total = results.length;
  console.log(`\n===== ${name} (${total}个词) =====`);
  api.CATEGORIES.filter(c => dist[c.id]).forEach(c => {
    const n = dist[c.id]; const pct = (n / total * 100).toFixed(1);
    const bar = '|'.repeat(Math.round(n / total * 30));
    console.log(`  ${(c.name + '     ').slice(0, 8)} ${String(n).padStart(4)}  ${bar} ${pct}%`);
  });
  const prod = ((dist.core || 0) + (dist.model || 0) + (dist.longtail || 0)) / total * 100;
  console.log(`  产品类合计: ${prod.toFixed(1)}%`);
  console.log(`  领域词根: ${[...api.state.learned].slice(0, 15).join(', ')}`);
  return dist;
}

