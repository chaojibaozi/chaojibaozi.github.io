function makeProxy() {
  const t = function () {};
  t.style = {}; t.dataset = {};
  t.classList = { add() {}, remove() {}, toggle() {}, contains() { return false; } };
  t.children = []; t.files = []; t.value = ''; t.textContent = ''; t.checked = false;
  t.appendChild = c => c; t.querySelectorAll = () => []; t.querySelector = () => makeProxy();
  t.addEventListener = () => {}; t.setAttribute = () => {}; t.getContext = () => null;
  return new Proxy(t, {
    get(o, p) { if (p in o) return o[p]; if (p === 'length') return 0; return makeProxy(); },
    set(o, p, v) { o[p] = v; return true; }
  });
}
const doc = { getElementById: () => makeProxy(), createElement: () => makeProxy(), addEventListener: () => {}, body: makeProxy() };
