// 通用细分面（对未在 EXPAND 中显式拆分、但值得再切的标签追加）
const GENERIC_FACETS = ['厂家', '批发', '价格', '加盟', '公司', '品牌', '定制'];

function normalize(name) {
  return name.replace(/\s+/g, '').trim();
}

function build(topLabels) {
  const set = new Map(); // finerName -> topLabel（保留来源，便于报告归类）
  for (const raw of topLabels) {
    const name = normalize(raw);
    if (!name) continue;
    if (EXPAND[name]) {
      for (const sub of EXPAND[name]) set.set(normalize(sub), name);
    } else {
      // 未显式拆分：保留原标签本身作为一个更细行业，避免遗漏
      set.set(name, name);
    }
  }
  return [...set.entries()].map(([finer, top]) => ({ finer, top }));
}

// ---- 用户原始标签（去重）----
const TOP_LABELS = fs.readFileSync(path.join(import.meta.dirname, 'industries_raw.txt'), 'utf-8')
  .split(/\s+/).map(s => s.trim()).filter(Boolean);

const finer = build(TOP_LABELS);
// 去重 finer 名
const seen = new Set(); const list = [];
for (const it of finer) { if (!seen.has(it.finer)) { seen.add(it.finer); list.push(it); } }

fs.writeFileSync(path.join(import.meta.dirname, 'finer_industries.json'), JSON.stringify(list, null, 0), 'utf-8');
console.log('原始标签数:', TOP_LABELS.length, '=> 更细行业数:', list.length);
